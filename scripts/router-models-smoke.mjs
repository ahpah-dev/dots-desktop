import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { resolve, join } from 'node:path';
import { mkdir, writeFile } from 'node:fs/promises';
const require = createRequire(import.meta.url), { _electron } = require('playwright');
const router = require(join(process.env.APPDATA, 'npm/node_modules/9router/src/cli/api/client.js'));
const catalog = await router.getModels();
assert.ok(catalog.success);
const expected = [...new Set(catalog.data.models.map(m => m.routedModel || m.fullModel).filter(Boolean))];
const output = resolve('artifacts/qa/router-models'); await mkdir(output, { recursive: true });
const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE;
const app = await _electron.launch({ executablePath: process.env.DOTS_SMOKE_EXECUTABLE || require('electron'), args: process.env.DOTS_SMOKE_EXECUTABLE ? ['--demo-mode'] : [resolve('.'), '--demo-mode'], env, timeout: 60000 });
const checks = [], errors = [];
const check = (name, value = true) => { assert.ok(value, name); checks.push(name); console.log(`PASS ${name}`); };
try {
  const page = await app.firstWindow(); page.on('pageerror', e => errors.push(e.message));
  await page.waitForSelector('.overview-dot-card');
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find(w => !w.webContents.getURL().includes('widget.html')).setSize(1360, 1040));
  const info = await page.evaluate(async root => {
    await window.dots.api.updateSettings({ desktopDotEnabled: false, desktopNotifications: false, defaultWorkspaceRoot: root });
    const profile = await window.dots.api.saveProviderProfile({ label: '9router', baseUrl: 'http://localhost:20128/v1', defaultModel: 'oc/muse-spark-1.3-contributor-free', requiresKey: false });
    const models = await window.dots.api.listModels(profile.id);
    const dot = await window.dots.api.createDot({ name: 'Router QA', description: '', instructions: '', color: '#78b7a0', emoji: '🌱', providerId: profile.id, model: profile.defaultModel, notify: false });
    return { profile, models, dot };
  }, join(output, 'workspaces'));
  check('All unique IDs in the live 9router catalog are returned', expected.every(id => info.models.some(m => m.id === id)) && info.models.length >= expected.length);
  const free = info.models.filter(m => m.id.startsWith('oc/'));
  check('Every OpenCode Free model is free and selectable, including Union Alpha', free.length >= 6 && free.every(m => m.free && m.available) && free.some(m => m.id === 'oc/union-alpha'));
  check('NVIDIA tool capabilities are recognized', info.models.filter(m => m.available && m.id.startsWith('nvidia/')).every(m => m.supportsTools === true));
  check('Models needing router setup are identified', info.models.some(m => m.available === false));
  await page.locator('.sidebar-dot').filter({ hasText: 'Router QA' }).click();
  await page.getByRole('button', { name: 'Profile', exact: true }).click();
  await page.getByRole('button', { name: 'Model & computer', exact: true }).click();
  const modelPicker = page.getByLabel('Model', { exact: true });
  await page.getByRole('button', { name: `Refresh models · ${info.models.length}`, exact: true }).waitFor();
  check('Profile lists the full catalog without losing the current model', await modelPicker.locator('option').count() === info.models.length + 1 && await modelPicker.inputValue() === info.dot.model);
  check('OpenCode Free has its own model group', await modelPicker.locator('optgroup[label="OpenCode Free"] option').count() === free.length);
  await modelPicker.selectOption('oc/space-bunny-free');
  await page.getByRole('button', { name: /Refresh models/ }).click();
  await page.getByRole('button', { name: `Refresh models · ${info.models.length}`, exact: true }).waitFor();
  check('Refresh preserves the selected model', await modelPicker.inputValue() === 'oc/space-bunny-free');
  await page.keyboard.press('Control+,');
  const settings = page.getByRole('dialog', { name: 'Settings', exact: true });
  await settings.getByRole('button', { name: 'Model providers', exact: true }).click();
  await settings.getByRole('button', { name: 'Edit 9router', exact: true }).click();
  await settings.getByRole('button', { name: 'Test connection & discover models', exact: true }).click();
  await settings.locator('.discovered-models button').nth(info.models.length - 1).waitFor();
  check('Provider setup shows every result beyond the old 60-model cutoff', await settings.locator('.discovered-models button').count() === info.models.length);
  await settings.getByLabel('Free only', { exact: true }).check();
  check('Free filter includes every OpenCode Free model', await settings.locator('.discovered-models button').filter({ hasText: 'oc/' }).count() === free.length);
  await settings.getByLabel('Search available models', { exact: true }).fill('muse-spark-1.3-contributor-free');
  check('OpenCode free model can be found and selected', await settings.locator('.discovered-models button').filter({ hasText: 'oc/muse-spark-1.3-contributor-free' }).count() === 1);
  await settings.screenshot({ path: join(output, 'free-models.png') });
  await page.keyboard.press('Escape');
  await page.keyboard.press('Control+n');
  const wizard = page.getByRole('dialog', { name: 'Meet your new dot', exact: true });
  await wizard.getByRole('button', { name: 'Continue', exact: true }).click();
  await wizard.getByLabel('Provider', { exact: true }).selectOption(info.profile.id);
  await wizard.getByRole('button', { name: 'Adjust model & tool settings', exact: true }).click();
  await wizard.getByRole('button', { name: `Refresh models · ${info.models.length}`, exact: true }).waitFor();
  check('New Dot lists the entire catalog and refresh control', await wizard.getByLabel('Model', { exact: true }).locator('option').count() === info.models.length + 1);
  await wizard.getByLabel('Model', { exact: true }).selectOption('oc/muse-spark-1.3-contributor-free');
  check('New Dot accepts OpenCode Free routing ID', await wizard.getByLabel('Custom model ID', { exact: true }).inputValue() === 'oc/muse-spark-1.3-contributor-free');
  check('No renderer errors', errors.length === 0);
  await writeFile(join(output, 'results.json'), JSON.stringify({ version: await app.evaluate(({ app }) => app.getVersion()), checks, errors, totalModels: info.models.length, openCodeFreeModels: free.map(m => m.id) }, null, 2));
} finally { await app.close(); }
